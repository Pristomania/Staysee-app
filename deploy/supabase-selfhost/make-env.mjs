// Creates deploy/supabase-selfhost/.env with fresh random secrets and the two legacy API keys (anon, service_role) signed with them.
// Never overwrites an existing .env. The file is in .gitignore: do not commit it, do not print it.
// Run: node make-env.mjs [--public-url https://host/supabase] [--site-url https://staysee.ru]
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, ".env");
if (existsSync(target)) {
  console.log(".env already exists: left untouched");
  process.exit(0);
}

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};

const b64url = (input) => Buffer.from(input).toString("base64url");
const sign = (payload, secret) => {
  const head = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = b64url(JSON.stringify(payload));
  const mac = createHmac("sha256", secret).update(`${head}.${body}`).digest("base64url");
  return `${head}.${body}.${mac}`;
};

const jwtSecret = randomBytes(32).toString("hex");
const now = Math.floor(Date.now() / 1000);
const tenYears = 10 * 365 * 24 * 3600;
const anon = sign({ role: "anon", iss: "supabase", iat: now, exp: now + tenYears }, jwtSecret);
const service = sign({ role: "service_role", iss: "supabase", iat: now, exp: now + tenYears }, jwtSecret);

const publicUrl = arg("--public-url", "http://127.0.0.1:8100");
const siteUrl = arg("--site-url", "http://127.0.0.1:5173");

const lines = [
  "# Generated by make-env.mjs. Secrets: never commit, never print.",
  `POSTGRES_PASSWORD=${randomBytes(24).toString("hex")}`,
  `JWT_SECRET=${jwtSecret}`,
  `ANON_KEY=${anon}`,
  `SERVICE_ROLE_KEY=${service}`,
  "JWT_EXPIRY=3600",
  `SUPABASE_PUBLIC_URL=${publicUrl}`,
  `API_EXTERNAL_URL=${publicUrl}`,
  `SITE_URL=${siteUrl}`,
  `ADDITIONAL_REDIRECT_URLS=${siteUrl}`,
  "DISABLE_SIGNUP=false",
  "# Rehearsal: true (no mail server). The real server: false + the Send Email hook (see README).",
  "ENABLE_EMAIL_AUTOCONFIRM=true",
  "DB_PORT_ON_HOST=54522",
  "API_PORT_ON_HOST=8100",
  "FUNCTIONS_MEMORY_LIMIT=1g",
  "",
];
writeFileSync(target, lines.join("\n"), { mode: 0o600 });
console.log(".env created (secrets not shown)");
