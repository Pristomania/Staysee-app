// Builds the texts the app shows (offer, privacy policy, consent) from the published documents in docs/legal.
// The .md files are the source; src/content/legal/{offer,privacy,consent}.ts are generated: run `npm run build:legal`
// after changing a document. A test fails if the committed files are out of date.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);

const DOCUMENTS = [
  { source: "docs/legal/ОФЕРТА-StaySee-2026-06-28.md", target: "src/content/legal/offer.ts", prefix: "OFFER", splitLevel: 2, withType: true },
  { source: "docs/legal/ПОЛИТИКА-ПД-StaySee-2026-06-28.md", target: "src/content/legal/privacy.ts", prefix: "PRIVACY_POLICY", splitLevel: 2 },
  { source: "docs/legal/СОГЛАСИЕ-НА-ОПД-StaySee-2026-06-28.md", target: "src/content/legal/consent.ts", prefix: "CONSENT", splitLevel: 3 },
];

const normalize = (text) => text.replace(/^﻿/, "").split("\r\n").join("\n");

/** Markdown to the plain text the document view shows (it keeps line breaks). */
export function mdToPlainText(md) {
  const lines = normalize(md).split("\n");
  const out = [];
  let tableRow = 0;
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (/^\s*-{3,}\s*$/.test(line)) {
      tableRow = 0;
      continue;
    }
    if (/^\s*\|/.test(line)) {
      const cells = line.trim().replace(/^\||\|$/g, "").split("|").map((cell) => cell.trim());
      const isSeparator = cells.every((cell) => /^:?-{2,}:?$/.test(cell));
      tableRow += 1;
      if (isSeparator || tableRow === 1) continue; // the header row and its underline
      out.push(`• ${cells.join(" — ")}`);
      continue;
    }
    tableRow = 0;
    out.push(line.replace(/^\s*[-*]\s+/, "• ").replace(/^#{3,6}\s+/, ""));
  }
  return out
    .join("\n")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/(^|[\s(])\*([^*\n]+?)\*(?=[\s).,;:]|$)/gm, "$1$2")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const sentenceCase = (text) => {
  const lower = text.toLowerCase();
  return lower.charAt(0).toUpperCase() + lower.slice(1);
};

/** Title, version, date and sections of a legal document. `splitLevel` is the heading level that starts a section. */
export function parseLegalDocument(md, { splitLevel }) {
  const text = normalize(md);
  const lines = text.split("\n");
  const title = (lines.find((line) => /^# /.test(line)) ?? "").replace(/^# /, "").trim();
  const subtitle = (lines.find((line) => /^## /.test(line)) ?? "").replace(/^## /, "").trim();
  const version = /\*\*Редакция:\*\*\s*([0-9.]+)/.exec(text)?.[1] ?? "";
  const effectiveDate = /\*\*Дата публикации:\*\*\s*([^\n]+?)\s*$/m.exec(text)?.[1] ?? "";

  const marker = "#".repeat(splitLevel) + " ";
  const subtitleIndex = lines.findIndex((line) => /^## /.test(line));
  const headingIndexes = lines
    .map((line, index) => (line.startsWith(marker) && !line.startsWith(marker + "#") && index !== subtitleIndex ? index : -1))
    .filter((index) => index >= 0);

  const sections = [];
  const firstHeading = headingIndexes[0] ?? lines.length;
  const metaLine = (line) => /^# /.test(line) || /^## /.test(line) || /\*\*(Редакция|Дата публикации):\*\*/.test(line);
  const preface = lines.slice(0, firstHeading).filter((line) => !metaLine(line)).join("\n");
  const prefacePlain = mdToPlainText(preface);
  if (prefacePlain) {
    const opening = /^\*\*([^*]+)\*\*\s*$/m.exec(preface);
    if (opening) {
      const bodyText = mdToPlainText(preface.replace(opening[0], ""));
      sections.push({ title: sentenceCase(opening[1].trim()), body: bodyText });
    } else {
      sections.push({ title: "Общие сведения", body: prefacePlain });
    }
  }
  headingIndexes.forEach((start, i) => {
    const end = headingIndexes[i + 1] ?? lines.length;
    sections.push({
      title: lines[start].slice(marker.length).trim(),
      body: mdToPlainText(lines.slice(start + 1, end).join("\n")),
    });
  });
  return { title, subtitle, version, effectiveDate, sections };
}

function renderFile({ source, prefix, withType }, doc, sha256) {
  const meta = { title: doc.title, subtitle: doc.subtitle, version: doc.version, effectiveDate: doc.effectiveDate, sha256 };
  const header = [
    `// GENERATED by scripts/build-legal-content.mjs from ${source}.`,
    "// Do not edit by hand: change the document and run `npm run build:legal`.",
    "",
  ];
  const type = withType
    ? ["export interface LegalSection {", "  title: string;", "  body: string;", "}", ""]
    : ["import type { LegalSection } from './offer';", ""];
  return [
    ...header,
    ...type,
    `export const ${prefix}_META = ${JSON.stringify(meta, null, 2)};`,
    "",
    `export const ${prefix}_SECTIONS: LegalSection[] = ${JSON.stringify(doc.sections, null, 2)};`,
    "",
  ].join("\n");
}

/** { "src/content/legal/offer.ts": "…", … } built from the documents on disk. */
export function buildLegalFiles() {
  const files = {};
  for (const document of DOCUMENTS) {
    const md = normalize(readFileSync(new URL(document.source, ROOT), "utf8"));
    const doc = parseLegalDocument(md, { splitLevel: document.splitLevel });
    const sha256 = createHash("sha256").update(md, "utf8").digest("hex");
    files[document.target] = renderFile(document, doc, sha256);
  }
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [path, content] of Object.entries(buildLegalFiles())) {
    writeFileSync(new URL(path, ROOT), content, "utf8");
    console.log(`written ${path}`);
  }
}
